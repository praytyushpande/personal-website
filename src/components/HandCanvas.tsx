export const WorldMapCanvas: React.FC = () => {
  const canvasRef = useRef<HTMLCanvasElement>(null);

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    if (!ctx) return;

    let animId: number;
    let time = 0;

    const resize = () => {
      if (!canvas) return;
      const dpr = window.devicePixelRatio || 1;
      canvas.width = window.innerWidth * dpr;
      canvas.height = window.innerHeight * dpr;
      canvas.style.width = window.innerWidth + 'px';
      canvas.style.height = window.innerHeight + 'px';
      ctx.scale(dpr, dpr);
    };

    window.addEventListener('resize', resize);
    resize();

    const rows = WORLD_MAP.length;
    const cols = WORLD_MAP[0].length;

    const render = () => {
      time += 0.008;
      const w = window.innerWidth;
      const h = window.innerHeight;
      const dpr = window.devicePixelRatio || 1;

      ctx.setTransform(1, 0, 0, 1, 0, 0);
      ctx.scale(dpr, dpr);
      ctx.clearRect(0, 0, w, h);

      // Calculate grid sizing to fill ~85% of the screen width, centered
      const mapWidth = w * 0.88;
      const dotSpacing = mapWidth / cols;
      const mapHeight = dotSpacing * rows;
      const offsetX = (w - mapWidth) / 2;
      const offsetY = (h - mapHeight) / 2;

      // Base dot radius scales with spacing
      const baseRadius = Math.max(1, dotSpacing * 0.32);

      // Clear zone around the center for the folder icon
      const centerX = w / 2;
      const centerY = h / 2;
      const clearRadius = Math.min(w, h) * 0.1;

      ctx.fillStyle = '#ffffff';

      for (let r = 0; r < rows; r++) {
        for (let c = 0; c < cols; c++) {
          if (WORLD_MAP[r][c] !== '1') continue;

          const x = offsetX + c * dotSpacing + dotSpacing / 2;
          const y = offsetY + r * dotSpacing + dotSpacing / 2;

          // Skip dots in the clear zone (where folder sits)
          const dx = x - centerX;
          const dy = y - centerY;
          const distFromCenter = Math.sqrt(dx * dx + dy * dy);
          if (distFromCenter < clearRadius) continue;

          // Subtle shimmer / breathing alpha
          const shimmer = Math.sin(time * 1.5 + r * 0.15 + c * 0.08) * 0.12;
          const alpha = Math.min(1, Math.max(0.25, 0.7 + shimmer));

          ctx.globalAlpha = alpha;
          ctx.beginPath();
          ctx.arc(x, y, baseRadius, 0, Math.PI * 2);
          ctx.fill();
        }
      }

      ctx.globalAlpha = 1;
      animId = requestAnimationFrame(render);
    };

    render();

    return () => {
      window.removeEventListener('resize', resize);
      cancelAnimationFrame(animId);
    };
  }, []);

  return (
    <canvas
      ref={canvasRef}
      style={{ position: 'fixed', inset: 0, width: '100%', height: '100%', pointerEvents: 'none', zIndex: 0 }}
    />
  );
};

export default WorldMapCanvas;
